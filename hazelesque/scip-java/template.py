def init_prepare(self):
    self.env["JAVA_HOME"] = "/usr/lib/jvm/java-21-openjdk"
    # Coursier defaults its cache to $HOME/.cache/coursier, which
    # lands in /tmp inside cports' bwrap (tmpfs, wiped between
    # phases).  Redirect to /builddir for persistence — same
    # pattern as bazel-7.4.0's --output_user_root.
    self.env["COURSIER_CACHE"] = "/builddir/.coursier-cache"
    # sbt also has its own caches.  Point them at /builddir too
    # so warm rebuilds are actually warm.
    self.env["SBT_OPTS"] = (
        "-Dsbt.global.base=/builddir/.sbt "
        "-Dsbt.boot.directory=/builddir/.sbt/boot "
        "-Dsbt.ivy.home=/builddir/.ivy2"
    )


def prepare(self):
    self.do(
        "./sbt",
        "cli/pack",
        env=self.env,
        allow_network=True,
    )


def build(self):
    pass


def install(self):
    self.install_license("LICENSE")
    # sbt-pack drops a runnable tree under scip-java/target/pack/
    # with bin/<launcher> and lib/<jar...>.  The launcher is
    # generated by sbt-pack with a relocation-safe PROG_HOME based
    # on `dirname $(readlink -f $0)`, so installing the whole tree
    # under /usr/share/scip-java and symlinking the launcher into
    # /usr/bin works without further patching.
    self.install_files("scip-java/target/pack/bin", "usr/share/scip-java")
    self.install_files("scip-java/target/pack/lib", "usr/share/scip-java")
    self.install_dir("usr/bin")
    self.install_link("usr/bin/scip-java", "../share/scip-java/bin/scip-java")
