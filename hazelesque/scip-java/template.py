    # via `PB.protocVersion`, which makes protocbridge fetch a
    # `protoc-linux-x86_64-3.17.3` from Maven that's glibc-linked
    # and won't exec on musl.  The ChimeraProtocOverride autoplugin
    # patched into project/ redirects PB.protocExecutable at the
    # system /usr/bin/protoc (5.32.x in cports today).  Wire
    # format and basic Java codegen are compatible across protoc
    # versions for the proto3 syntax scip-java uses.  protobuf-
    # protoc is the subpackage that ships /usr/bin/protoc; the
    # `protobuf` package itself is just the runtime libraries.
