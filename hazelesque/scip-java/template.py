# SCIP indexer for Java, Scala, and Kotlin.  Source-built via the
# in-tree `./sbt` -> `./bin/coursier launch sbt` -> sbt 1.11 ->
# scalac chain that scip-java upstream ships.  Result is an
# sbt-pack tree (launcher + jars) under scip-java/target/pack/;
# we install the lib/ jars under /usr/share/scip-java/ and the
# generated launcher at /usr/bin/scip-java.
#
# About the build infrastructure scip-java ships in-tree:
#
#   - bin/coursier (159 KB) — a self-contained sh+ZIP launcher
#     for Coursier (Java bytecode in a JAR with a shell stub).
#     Pure JVM bytecode, runs anywhere a JDK does.  This is build
#     infrastructure that came with the upstream tarball, same
#     status as any project's checked-in bootstrap script (cf.
#     bazel's compile.sh, gradle's gradle-wrapper.jar) — not a
#     binary blob we are slapping on.
#
#   - ./sbt — three-line script that does
#     `./bin/coursier launch --jvm 11 sbt`.  Patched here to drop
#     `--jvm 11` (Coursier would try to download JDK 11 from
#     cdn.azul.com; we have no JDK 11 locally and the sandbox
#     blocks that download anyway).  sbt 1.11 runs fine on JDK 21.
#
# Network is required during prepare() because Coursier resolves
# ~hundreds of Maven artifacts from Maven Central at build time
# (scalameta, scala-xml, kotlin-compiler-embeddable, etc.).  Same
# pattern as bazel-7.4.0-bootstrap, with the same TODO to vendor
# the maven cache into source = [...] entries for sealed offline
# builds.

